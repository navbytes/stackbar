// Reads the facts the site shares with Stackbar straight from the Swift
// sources, so they are written once: the design-system hues, spacing and radii
// (StackbarKit/Design.swift), the official store's URL and publisher key
// (StackbarHostCore/OfficialIndex.swift), the app version and the app icon.
// Each reader fails loudly when the Swift no longer looks the way it expects,
// rather than letting the site drift.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const read = (relative) => fs.readFileSync(path.join(repoRoot, relative), 'utf8');

function need(value, what, file) {
  if (value === undefined || value === null || (Array.isArray(value) && value.length === 0)) {
    throw new Error(`site: couldn't read ${what} from ${file}; update site/scripts/kit.mjs to match it`);
  }
  return value;
}

/** `public enum <name> { public static let <key> = <number> ... }` */
function numberEnum(source, name, file) {
  const block = source.match(new RegExp(`public enum ${name} \\{([\\s\\S]*?)\\n\\}`))?.[1];
  need(block, `enum ${name}`, file);
  const values = {};
  for (const [, key, value] of block.matchAll(/public static let (\w+) = ([\d.]+)/g)) values[key] = Number(value);
  return need(Object.keys(values).length ? values : undefined, `${name} values`, file);
}

export function readDesign(source = read('Sources/StackbarKit/Design.swift')) {
  const file = 'Sources/StackbarKit/Design.swift';
  const hues = {};
  const theme = /public static let (\w+) = Theme\("(#[0-9A-Fa-f]{6})", dark: "(#[0-9A-Fa-f]{6})", soft: "(#[0-9A-Fa-f]{6})", darkSoft: "(#[0-9A-Fa-f]{6})"\)/g;
  for (const [, name, light, dark, soft, darkSoft] of source.matchAll(theme)) hues[name] = { light, dark, soft, darkSoft };
  if (Object.keys(hues).length < 11) need(undefined, 'the eleven Theme hues', file);
  const aliases = {};
  for (const [, alias, target] of source.matchAll(/public static let (\w+) = (\w+)\n/g)) {
    if (hues[target] && !hues[alias]) aliases[alias] = target;
  }
  return { hues, aliases, space: numberEnum(source, 'Space', file), radius: numberEnum(source, 'Radius', file) };
}

export function readStore(source = read('Sources/StackbarHostCore/OfficialIndex.swift')) {
  const file = 'Sources/StackbarHostCore/OfficialIndex.swift';
  return {
    name: need(source.match(/static let name = "([^"]+)"/)?.[1], 'the store name', file),
    indexURL: need(source.match(/static let url = URL\(string: "([^"]+)"\)/)?.[1], 'the index URL', file),
    repository: need(source.match(/static let repository = URL\(string: "([^"]+)"\)/)?.[1], 'the repository', file),
    publicKey: need(source.match(/static let publicKey: String\? = "([^"]+)"/)?.[1], 'the publisher key', file),
  };
}

/** The three bar gradients of the app icon: the brand colours. */
export function readBrand(source = read('Packaging/Icon/AppIcon.svg')) {
  const brand = {};
  for (const id of ['b1', 'b2', 'b3']) {
    const block = source.match(new RegExp(`<linearGradient id="${id}"[\\s\\S]*?</linearGradient>`))?.[0];
    const stops = [...(block ?? '').matchAll(/stop-color="(#[0-9A-Fa-f]{6})"/g)].map((m) => m[1]);
    brand[id] = need(stops.length === 2 ? stops : undefined, `icon gradient ${id}`, 'Packaging/Icon/AppIcon.svg');
  }
  return brand;
}

export function readVersion(source = read('Sources/StackbarHostCore/StackbarVersion.swift')) {
  return need(source.match(/static let current = "([^"]+)"/)?.[1], 'the version', 'StackbarVersion.swift');
}

/** CSS custom properties for every hue, switching with the colour scheme. */
export function designCSS({ hues, aliases, space, radius }, brand) {
  const lines = ['/* Generated by site/scripts/sync-kit.mjs from StackbarKit/Design.swift. and Packaging/Icon/AppIcon.svg. Do not edit. */', ':root {'];
  for (const [name, h] of Object.entries(hues)) {
    lines.push(`  --kit-${name}-light: ${h.light};`, `  --kit-${name}-dark: ${h.dark};`,
      `  --kit-${name}-soft-light: ${h.soft};`, `  --kit-${name}-soft-dark: ${h.darkSoft};`,
      `  --kit-${name}: light-dark(${h.light}, ${h.dark});`, `  --kit-${name}-soft: light-dark(${h.soft}, ${h.darkSoft});`);
  }
  for (const [alias, target] of Object.entries(aliases)) lines.push(`  --kit-${alias}: var(--kit-${target});`, `  --kit-${alias}-soft: var(--kit-${target}-soft);`);
  for (const [k, v] of Object.entries(space)) lines.push(`  --kit-space-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(radius)) lines.push(`  --kit-radius-${k}: ${v}px;`);
  if (brand) Object.values(brand).forEach(([from, to], i) => lines.push(`  --brand-${i + 1}-from: ${from};`, `  --brand-${i + 1}-to: ${to};`));
  lines.push('}', '');
  return lines.join('\n');
}
