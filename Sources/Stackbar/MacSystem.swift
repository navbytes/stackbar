#if os(macOS)
import AppKit
import ApplicationServices
import EventKit
import IOKit.ps
import IOKit.pwr_mgt
import StackbarHostCore
import StackbarProtocol

/// The clipboard, power assertions, battery, running apps and calendar for
/// plugins, read from AppKit, IOKit and EventKit. `HostServices` checks each
/// plugin's capabilities before anything here runs.
final class MacSystem: SystemServices, @unchecked Sendable {
    private let lock = NSLock()
    private var assertions: [String: [IOPMAssertionID]] = [:]
    private let images: ClipboardImageStore
    private let store = EKEventStore()
    /// The last app the user was in that wasn't Stackbar: where a paste goes,
    /// and what a copy came from when Stackbar itself is frontmost.
    @MainActor private var previousApp: NSRunningApplication?
    @MainActor private var observer: NSObjectProtocol?

    init(images: ClipboardImageStore) {
        self.images = images
        Task { @MainActor in self.watchActivations() }
    }

    @MainActor private func watchActivations() {
        previousApp = NSWorkspace.shared.frontmostApplication.flatMap { $0.processIdentifier == getpid() ? nil : $0 }
        observer = NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] note in
            guard let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication, app.processIdentifier != getpid() else { return }
            MainActor.assumeIsolated { self?.previousApp = app }
        }
    }

    // MARK: Clipboard

    private static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType"),
    ]

    func clipboardChangeCount() -> Int {
        onMain { NSPasteboard.general.changeCount }
    }

    func readClipboard() -> ClipboardItem? {
        onMain { () -> ClipboardItem? in
            let board = NSPasteboard.general
            let types = Set(board.types ?? [])
            guard !types.isEmpty else { return nil }
            let frontmost = NSWorkspace.shared.frontmostApplication
            let source = frontmost?.processIdentifier == getpid() ? nil : frontmost
            var item = ClipboardItem(changeCount: board.changeCount, kind: .text, sourceAppID: source?.bundleIdentifier ?? (frontmost == nil ? nil : "io.navbytes.stackbar"), sourceAppName: source?.localizedName ?? (frontmost == nil ? nil : "Stackbar"))
            if !types.isDisjoint(with: Self.concealedTypes) {
                item.concealed = true
                return item
            }
            if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
                item.kind = .files
                item.files = urls.map(\.path)
                item.text = item.files.joined(separator: "\n")
                return item
            }
            if let string = board.string(forType: .string) {
                let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
                let isURL = !trimmed.contains(where: \.isWhitespace) && (trimmed.hasPrefix("https://") || trimmed.hasPrefix("http://"))
                item.kind = isURL ? .url : .text
                item.text = String(string.prefix(200_000))
                // Keep formatting (rich text, HTML, an app's own types) so a
                // paste puts back exactly what was copied.
                if !types.subtracting(Self.plainTypes).isEmpty, let snapshot = Self.snapshot(board) {
                    item.contentID = try? images.save(snapshot)
                }
                return item
            }
            if let data = board.data(forType: .png) ?? board.data(forType: .tiff), data.count < 32 * 1024 * 1024, let bitmap = NSBitmapImageRep(data: data), let png = bitmap.representation(using: .png, properties: [:]) {
                item.kind = .image
                item.imageID = try? images.save(png)
                item.imageSize = [bitmap.pixelsWide, bitmap.pixelsHigh]
                return item.imageID == nil ? nil : item
            }
            return nil
        }
    }

    /// Types that carry nothing beyond the plain string itself.
    private static let plainTypes: Set<NSPasteboard.PasteboardType> = [
        .string, .init("NSStringPboardType"), .init("public.utf16-external-plain-text"), .init("public.utf16-plain-text"),
        .init("org.nspasteboard.source"), .URL, .init("public.url-name"), .init("NSURLPboardType"),
    ]

    /// Every type of every pasteboard item, as a property list, up to 20 MB.
    private static func snapshot(_ board: NSPasteboard) -> Data? {
        var items: [[String: Data]] = []
        var total = 0
        for pasteboardItem in board.pasteboardItems ?? [] {
            var entry: [String: Data] = [:]
            for type in pasteboardItem.types {
                guard let data = pasteboardItem.data(forType: type) else { continue }
                total += data.count
                guard total <= 20 * 1024 * 1024 else { return nil }
                entry[type.rawValue] = data
            }
            items.append(entry)
        }
        return items.isEmpty ? nil : try? PropertyListEncoder().encode(items)
    }

    func writeClipboard(_ content: ClipboardContent) throws {
        var imageData: Data?
        var storedItems: [[String: Data]]?
        switch content {
        case .image(let id):
            guard let data = images.data(for: id) else { throw SystemServiceError("that image is no longer kept; copy it again") }
            imageData = data
        case .stored(let id):
            guard let data = images.data(for: id), let items = try? PropertyListDecoder().decode([[String: Data]].self, from: data) else {
                throw SystemServiceError("that item's formatting is no longer kept; paste it as plain text")
            }
            storedItems = items
        case .text, .files:
            break
        }
        onMain {
            let board = NSPasteboard.general
            board.clearContents()
            switch content {
            case .text(let text): board.setString(text, forType: .string)
            case .files(let paths): board.writeObjects(paths.map { URL(fileURLWithPath: $0) as NSURL })
            case .image: if let imageData { board.setData(imageData, forType: .png) }
            case .stored:
                let items = (storedItems ?? []).map { types -> NSPasteboardItem in
                    let item = NSPasteboardItem()
                    for (type, data) in types { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
                    return item
                }
                board.writeObjects(items)
            }
        }
    }

    func paste(_ content: ClipboardContent) async throws {
        try writeClipboard(content)
        let trusted = await MainActor.run { AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary) }
        guard trusted else {
            throw SystemServiceError("copied, but Stackbar needs Accessibility access to paste: System Settings > Privacy & Security > Accessibility")
        }
        await MainActor.run {
            NSApp.hide(nil)
            previousApp?.activate()
        }
        try? await Task.sleep(for: .milliseconds(200))
        await MainActor.run {
            let source = CGEventSource(stateID: .combinedSessionState)
            let vKey: CGKeyCode = 9 // kVK_ANSI_V
            for isDown in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: isDown)
                event?.flags = .maskCommand
                event?.post(tap: .cgAnnotatedSessionEventTap)
            }
        }
    }

    // MARK: Power

    func keepAwake(_ request: KeepAwakeRequest?, pluginID: String) throws {
        try lock.withLock {
            for id in assertions.removeValue(forKey: pluginID) ?? [] { IOPMAssertionRelease(id) }
            guard let request else { return }
            var held: [IOPMAssertionID] = []
            let kinds = request.display ? ["PreventUserIdleDisplaySleep", "PreventUserIdleSystemSleep"] : ["PreventUserIdleSystemSleep"]
            for kind in kinds {
                var id = IOPMAssertionID(0)
                let result = IOPMAssertionCreateWithName(kind as CFString, IOPMAssertionLevel(kIOPMAssertionLevelOn), request.reason as CFString, &id)
                guard result == kIOReturnSuccess else {
                    for id in held { IOPMAssertionRelease(id) }
                    throw SystemServiceError("macOS refused the power assertion (\(result))")
                }
                held.append(id)
            }
            assertions[pluginID] = held
        }
    }

    func systemStatus() -> SystemStatus {
        var status = SystemStatus()
        if let info = IOPSCopyPowerSourcesInfo()?.takeRetainedValue() {
            if let providing = IOPSGetProvidingPowerSourceType(info)?.takeUnretainedValue() {
                status.onACPower = (providing as String) == "AC Power"
            }
            let sources = (IOPSCopyPowerSourcesList(info)?.takeRetainedValue() as? [CFTypeRef]) ?? []
            for source in sources {
                guard let description = IOPSGetPowerSourceDescription(info, source)?.takeUnretainedValue() as? [String: Any],
                      description["Type"] as? String == "InternalBattery" else { continue }
                if let current = description["Current Capacity"] as? Int, let maximum = description["Max Capacity"] as? Int, maximum > 0 {
                    status.batteryLevel = min(1, Double(current) / Double(maximum))
                }
                status.charging = description["Is Charging"] as? Bool ?? false
            }
        }
        status.lowPowerMode = ProcessInfo.processInfo.isLowPowerModeEnabled
        status.runningApps = onMain {
            NSWorkspace.shared.runningApplications
                .filter { $0.activationPolicy == .regular && $0.processIdentifier != getpid() }
                .compactMap { app in app.bundleIdentifier.map { SystemStatus.App(id: $0, name: app.localizedName ?? $0) } }
        }
        status.keptAwakeBy = lock.withLock { assertions.keys.sorted() }
        status.externalDisplays = Self.externalDisplayCount()
        let network = Self.networkCounters()
        status.networkBytesReceived = network.received
        status.vpnActive = network.vpn
        return status
    }

    /// Active displays that aren't the built-in panel.
    static func externalDisplayCount() -> Int {
        var count: UInt32 = 0
        guard CGGetActiveDisplayList(0, nil, &count) == .success, count > 0 else { return 0 }
        var displays = [CGDirectDisplayID](repeating: 0, count: Int(count))
        guard CGGetActiveDisplayList(count, &displays, &count) == .success else { return 0 }
        return displays.prefix(Int(count)).filter { CGDisplayIsBuiltin($0) == 0 }.count
    }

    /// Bytes received across physical interfaces since boot, and whether a
    /// tunnel interface carries an IPv4 address (macOS's own utuns, used by
    /// iCloud and Handoff, only have IPv6 link-local addresses).
    static func networkCounters() -> (received: UInt64, vpn: Bool) {
        var received: UInt64 = 0
        var vpn = false
        var list: UnsafeMutablePointer<ifaddrs>?
        guard getifaddrs(&list) == 0, let first = list else { return (0, false) }
        defer { freeifaddrs(list) }
        for pointer in sequence(first: first, next: { $0.pointee.ifa_next }) {
            let entry = pointer.pointee
            guard let address = entry.ifa_addr, entry.ifa_flags & UInt32(IFF_UP) != 0 else { continue }
            let name = String(cString: entry.ifa_name)
            let tunnel = name.hasPrefix("utun") || name.hasPrefix("ipsec") || name.hasPrefix("ppp")
            if tunnel, address.pointee.sa_family == UInt8(AF_INET) { vpn = true }
            if address.pointee.sa_family == UInt8(AF_LINK), !tunnel, !name.hasPrefix("lo"), let data = entry.ifa_data {
                received &+= UInt64(data.assumingMemoryBound(to: if_data.self).pointee.ifi_ibytes)
            }
        }
        return (received, vpn)
    }

    // MARK: Calendar

    func calendarEvents(from: Date, to: Date) async throws -> [CalendarEvent] {
        guard Bundle.main.object(forInfoDictionaryKey: "NSCalendarsFullAccessUsageDescription") != nil else {
            throw SystemServiceError("calendar access needs Stackbar.app (scripts/bundle.sh); an unbundled build has no Info.plist to ask with")
        }
        switch EKEventStore.authorizationStatus(for: .event) {
        case .fullAccess:
            break
        case .notDetermined:
            guard try await store.requestFullAccessToEvents() else {
                throw SystemServiceError("calendar access was declined; allow Stackbar in System Settings > Privacy & Security > Calendars")
            }
        default:
            throw SystemServiceError("Stackbar has no full access to your calendars; allow it in System Settings > Privacy & Security > Calendars")
        }
        let predicate = store.predicateForEvents(withStart: from, end: to, calendars: nil)
        return store.events(matching: predicate).map(Self.event).sorted { $0.start < $1.start }
    }

    private static func event(_ event: EKEvent) -> CalendarEvent {
        let start: Date = event.startDate ?? Date()
        let title: String = event.title ?? ""
        let attendees = event.attendees ?? []
        var participation = CalendarEvent.Participation.none
        if let me = attendees.first(where: \.isCurrentUser) {
            switch me.participantStatus {
            case .accepted: participation = .accepted
            case .declined: participation = .declined
            case .tentative: participation = .tentative
            case .pending: participation = .pending
            default: participation = .none
            }
        }
        return CalendarEvent(
            id: (event.eventIdentifier ?? event.calendarItemIdentifier) + "@" + String(Int(start.timeIntervalSince1970)),
            title: title.isEmpty ? "(No title)" : title,
            start: start,
            end: event.endDate ?? start,
            isAllDay: event.isAllDay,
            location: event.location,
            notes: event.notes.map { String($0.prefix(4000)) },
            url: event.url?.absoluteString,
            calendar: event.calendar?.title ?? "Calendar",
            calendarColor: event.calendar?.cgColor.flatMap(hex),
            participation: participation,
            attendees: attendees.count,
            organizer: event.organizer?.name
        )
    }

    private static func hex(_ color: CGColor) -> String? {
        guard let rgb = NSColor(cgColor: color)?.usingColorSpace(.sRGB) else { return nil }
        let value = { (component: CGFloat) in Int((component * 255).rounded()) }
        return String(format: "#%02X%02X%02X", value(rgb.redComponent), value(rgb.greenComponent), value(rgb.blueComponent))
    }

    private func onMain<T: Sendable>(_ body: @MainActor () -> T) -> T {
        if Thread.isMainThread { return MainActor.assumeIsolated(body) }
        return DispatchQueue.main.sync { MainActor.assumeIsolated(body) }
    }
}
